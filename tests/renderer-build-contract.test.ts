import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { PWA_DISPLAY_NAME } from "../shared/product-branding.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function read(relPath) {
  return fs.readFileSync(path.join(ROOT, relPath), "utf8");
}

describe("renderer build contracts", () => {
  it("uses Vite 8 codeSplitting=false instead of deprecated inlineDynamicImports", () => {
    const configs = [
      "vite.config.main.js",
      "vite.config.server.js",
      "vite.config.theme.js",
    ];

    for (const configPath of configs) {
      const config = read(configPath);
      expect(config, `${configPath} should not use deprecated inlineDynamicImports`)
        .not.toContain("inlineDynamicImports");
      expect(config, `${configPath} should explicitly preserve single-file output`)
        .toContain("codeSplitting: false");
    }
  });

  it("loads legacy renderer globals as module scripts so Vite can process HTML without legacy-script warnings", () => {
    const pageScripts = new Map([
      ["index", ["lib/i18n.js", "lib/theme.js", "modules/platform.js"]],
      ["settings", ["lib/i18n.js", "lib/theme.js", "modules/platform.js"]],
      ["onboarding", ["lib/i18n.js", "lib/theme.js", "modules/platform.js"]],
      ["browser-viewer", ["lib/i18n.js", "lib/theme.js", "modules/platform.js"]],
      ["mobile", ["lib/i18n.js", "lib/theme.js"]],
      ["quick-chat", ["lib/i18n.js", "lib/theme.js", "modules/platform.js"]],
    ]);

    for (const [page, scripts] of pageScripts) {
      const html = read(`desktop/src/${page}.html`);
      for (const src of scripts) {
        const escaped = src.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        expect(
          html,
          `${page}.html should load ${src} with type="module"`,
        ).toMatch(new RegExp(`<script\\s+type="module"\\s+src="${escaped}"\\s*><\\/script>`));
      }
    }
  });

  it("keeps KaTeX and markdown-it in separate manual chunks instead of one oversized markdown vendor chunk", () => {
    const config = read("vite.config.ts");

    expect(config).toContain("katex-vendor");
    expect(config).toContain("markdown-it-vendor");
    expect(config).not.toContain("return 'markdown-vendor'");
  });

  it("builds a dedicated themed mobile shell for Access & Devices mobile URLs", () => {
    const config = read("vite.config.ts");
    const html = read("desktop/src/mobile.html");
    const entry = read("desktop/src/mobile-main.tsx");

    expect(config).toContain("'mobile.html'");
    expect(config).toContain("mobile: path.join(rendererRoot, 'mobile.html')");
    expect(config).toContain("mobile-manifest.webmanifest");
    expect(config).toContain("mobile-sw.ts");

    expect(html).toContain(`<title>${PWA_DISPLAY_NAME}</title>`);
    expect(html).toContain('<div id="react-root"></div>');
    expect(html).not.toContain('href="styles.css"');
    expect(html).toContain('href="themes/codia-lilac.css" id="themeSheet"');
    expect(html).toContain('src="./mobile-main.tsx"');

    expect(entry).toContain("__CODIA_PWA__");
    expect(entry).toContain("serverUrl");
    expect(entry).toContain("wsUrl");
    expect(entry).toContain("installMobilePlatform");
    expect(entry).toContain("./react/mobile/mobile-entry.css");
    expect(entry).not.toContain("./styles.css");
    expect(entry).toContain("import('./react/mobile/MobileApp')");
  });

  it("keeps quick chat on the fixed Codia theme stylesheet", () => {
    const html = read("desktop/src/quick-chat.html");

    expect(html).toContain('href="themes/codia-lilac.css" id="themeSheet"');
    expect(html).not.toContain("themes/warm-paper.css");
  });

  it("keeps provider icon generation wired for the model selector", () => {
    const generator = read("scripts/gen-provider-icons.mjs");
    const icons = read("desktop/src/react/ui/provider-icons.ts");

    expect(generator).toContain("@lobehub/icons-static-svg");
    expect(generator).toContain("desktop/src/react/ui/provider-icons.ts");
    expect(generator).toContain("'deepseek'");
    expect(generator).toContain("'openai'");

    expect(icons).toContain("Auto-generated by scripts/gen-provider-icons.mjs");
    expect(icons).toContain("export const PROVIDER_ICONS");
    expect(icons).toContain('"deepseek"');
    expect(icons).toContain('"openai"');
  });

  it("keeps legacy browser runtime sources in TypeScript while preserving JS load paths", () => {
    for (const source of [
      "desktop/src/lib/i18n",
      "desktop/src/lib/theme",
      "desktop/src/modules/platform",
      "desktop/src/modules/connection-csp",
      "desktop/src/mobile-sw",
    ]) {
      expect(fs.existsSync(path.join(ROOT, `${source}.ts`)), `${source}.ts`).toBe(true);
      expect(fs.existsSync(path.join(ROOT, `${source}.js`)), `${source}.js`).toBe(false);
    }

    const config = read("vite.config.ts");
    expect(config).toContain("RUNTIME_SCRIPT_BUILDS");
    expect(config).toContain("lib/i18n.ts");
    expect(config).toContain("modules/platform.ts");
    expect(config).toContain("mobile-sw.ts");
  });
});
