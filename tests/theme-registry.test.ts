import { describe, expect, it } from "vitest";
import fs from "node:fs";
import path from "node:path";
import registry from "../desktop/src/shared/theme-registry.cjs";

const themesDir = path.resolve("desktop/src/themes");

describe("theme registry", () => {
  it("keeps theme metadata complete", () => {
    expect(registry.DEFAULT_THEME).toBe("codia-lilac");
    expect(Object.keys(registry.THEMES)).not.toContain("claude-design");
    expect(Object.keys(registry.THEMES)).toEqual([
      "codia-lilac",
    ]);
    for (const [id, entry] of Object.entries(registry.THEMES)) {
      expect(id).toBeTruthy();
      expect(entry.cssPath).toMatch(/^themes\/.+\.css$/);
      expect(entry.backgroundColor).toMatch(/^#[0-9A-F]{6}$/i);
      expect(entry.preview).toEqual({
        surface: expect.stringMatching(/^#[0-9A-F]{6}$/i),
        text: expect.stringMatching(/^#[0-9A-F]{6}$/i),
        muted: expect.stringMatching(/^#[0-9A-F]{6}$/i),
        accent: expect.stringMatching(/^#[0-9A-F]{6}$/i),
      });
      expect(entry.i18nName).toMatch(/^settings\.appearance\./);
      expect(entry.i18nMode).toMatch(/^settings\.appearance\./);
    }
  });

  it("migrates invalid saved themes to the default", () => {
    expect(registry.migrateSavedTheme("auto")).toBe("codia-lilac");
    expect(registry.migrateSavedTheme("midnight")).toBe("codia-lilac");
    expect(registry.migrateSavedTheme("warm-paper")).toBe("codia-lilac");
    expect(registry.migrateSavedTheme("sage-workbench")).toBe("codia-lilac");
    expect(registry.migrateSavedTheme("claude-design")).toBe("codia-lilac");
    expect(registry.migrateSavedTheme("missing-theme")).toBe(registry.DEFAULT_THEME);
    expect(registry.migrateSavedTheme(null)).toBe(registry.DEFAULT_THEME);
  });

  it("normalizes auto to the fixed lilac theme", () => {
    expect(registry.resolveSavedTheme("auto", false)).toEqual({
      stored: "codia-lilac",
      concrete: "codia-lilac",
    });
    expect(registry.resolveSavedTheme("auto", true)).toEqual({
      stored: "codia-lilac",
      concrete: "codia-lilac",
    });
  });

  it("resolves auto defaults to light and dark concrete themes", () => {
    expect(registry.AUTO_LIGHT_DEFAULT).toBe("codia-lilac");
    expect(registry.AUTO_DARK_DEFAULT).toBe("codia-lilac");
  });

  it("declares themes that suppress paper texture for UI readability", () => {
    expect(registry.PAPER_TEXTURE_BLOCKED_THEME_IDS).toEqual(
      expect.arrayContaining(Object.keys(registry.THEMES)),
    );
    for (const themeId of Object.keys(registry.THEMES)) {
      expect(registry.isPaperTextureBlockedTheme(themeId)).toBe(true);
    }
  });

  it("keeps only active selectable theme stylesheets on disk", () => {
    const expected = new Set([
      "codia-lilac.css",
      "studio-light.css",
      "midnight.css",
      "midnight-contrast.css",
      "nocturne.css",
      "workbench.css",
      "precision-ide.css",
      "coral.css",
      "claude-design-fonts.css",
      "new-warm-paper-fonts.css",
    ]);
    const cssFiles = fs.readdirSync(themesDir).filter((name) => name.endsWith(".css"));
    expect(cssFiles.sort()).toEqual([...expected].sort());
  });

  it("keeps the source browser theme runtime in TypeScript and wired to the shared registry", () => {
    const runtimeSource = fs.readFileSync(path.resolve("desktop/src/lib/theme.ts"), "utf-8");
    const sharedRuntimeSource = fs.readFileSync(path.resolve("desktop/src/shared/theme.ts"), "utf-8");
    expect(runtimeSource).toContain("Generated by scripts/sync-theme-runtime.mjs");
    expect(runtimeSource).toContain("../shared/theme.ts");
    expect(sharedRuntimeSource).toContain("theme-registry");
    expect(runtimeSource).not.toContain("const _THEMES = {");
    expect(runtimeSource).not.toContain("const _LEGACY_THEME_ALIASES = {");
    expect(fs.existsSync(path.resolve("desktop/src/lib/theme.js"))).toBe(false);
  });

  it("keeps build:theme guarded by the runtime sync script", () => {
    const packageJson = JSON.parse(fs.readFileSync(path.resolve("package.json"), "utf-8"));
    expect(packageJson.scripts["build:theme"]).toContain("sync-theme-runtime.mjs");
  });
});
