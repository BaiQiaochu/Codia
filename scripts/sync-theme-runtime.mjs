import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const root = path.resolve(path.dirname(__filename), "..");
const target = path.join(root, "desktop", "src", "lib", "theme.ts");

const source = `// Generated by scripts/sync-theme-runtime.mjs.
// The browser runtime source of truth is desktop/src/shared/theme.ts,
// which imports theme-registry.cjs for theme metadata.
import "../shared/theme.ts";
`;

const current = fs.existsSync(target) ? fs.readFileSync(target, "utf-8") : "";
if (current !== source) {
  fs.writeFileSync(target, source, "utf-8");
  console.log("[sync-theme-runtime] updated desktop/src/lib/theme.ts");
}
