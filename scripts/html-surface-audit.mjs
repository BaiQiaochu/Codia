#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const args = process.argv.slice(2);
const jsonOnly = args.includes("--json");
const help = args.includes("--help") || args.includes("-h");
const reportArg = args.find((arg) => arg.startsWith("--report="));
const markdownArg = args.find((arg) => arg.startsWith("--markdown="));
const reportPath = reportArg ? path.resolve(reportArg.slice("--report=".length)) : null;
const markdownPath = markdownArg ? path.resolve(markdownArg.slice("--markdown=".length)) : null;

const SCAN_ROOTS = [
  "desktop/src/react",
  "server",
  "core",
  "lib",
  "shared",
  "plugins",
];

const EXTENSIONS = new Set([".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx"]);
const SKIP_DIRS = new Set([
  "node_modules",
  "dist",
  "dist-server",
  "dist-renderer",
  "dist-server-bundle",
  "artifacts",
  ".cache",
]);

const SAFE_HTML_HELPERS = [
  "renderMarkdown(",
  "renderMarkdownPreview(",
  "sanitizeMarkdownPreviewHtml(",
  "fileIconSvg(",
  "ICONS.",
  "icon.content",
  "cmd.icon",
  "itemIcon",
  "__html: d",
  "html }}",
  "step }}",
  "artifact.content",
];

function allowedDangerousHtmlReason(fileRel, source) {
  if (fileRel.endsWith("components/chat/MarkdownContent.tsx")) {
    return "chat markdown HTML is produced by the central sanitized markdown renderer before this display component";
  }
  if (fileRel.endsWith("components/SkillViewerOverlay.tsx") && source.includes("__html: rendered")) {
    return "skill viewer markdown HTML is produced by renderMarkdownPreview() before assignment to the rendered preview";
  }
  if (source.includes("renderMarkdown(") || source.includes("renderMarkdownPreview(") || source.includes("sanitizeMarkdownPreviewHtml(")) {
    return "markdown preview HTML is routed through the central sanitized markdown renderer";
  }
  if (source.includes("ICONS.") || source.includes("fileIconSvg(") || source.includes("cmd.icon") || source.includes("itemIcon") || source.includes("icon.content") || source.includes("__html: d")) {
    return "inline SVG icon markup comes from static application icon registries, not user input";
  }
  if ((fileRel.endsWith("components/preview/ArtifactRenderer.tsx")
      || fileRel.endsWith("components/preview/PreviewRenderer.tsx"))
    && source.includes("artifact.content")) {
    return "artifact docx/xlsx/design preview HTML is generated by trusted local converters and constrained to the preview pane";
  }
  if (source.includes("step }}")) {
    return "bridge tutorial steps are localized static HTML snippets controlled by the app";
  }
  if (source.includes("html }}")) {
    return "memory viewer HTML is generated from sanitized markdown before render";
  }
  return "";
}

function allowedIframeReason(fileRel, source) {
  if (fileRel.endsWith("components/plugin/PluginWidgetView.tsx")) {
    return "plugin widget iframe is the intentional sandboxed plugin isolation boundary";
  }
  if (fileRel.endsWith("components/plugin/PluginPageView.tsx")) {
    return "plugin page iframe is the intentional sandboxed plugin isolation boundary";
  }
  if (fileRel.endsWith("components/chat/PluginCardBlock.tsx")) {
    return "chat plugin card iframe is isolated by sandbox attributes before rendering plugin output";
  }
  if ((fileRel.endsWith("components/preview/ArtifactRenderer.tsx")
      || fileRel.endsWith("components/preview/PreviewRenderer.tsx"))
    && source.includes("preview-pdf")) {
    return "PDF iframe displays a blob/file URL preview with browser PDF viewer chrome disabled";
  }
  if (fileRel.endsWith("components/preview/ArtifactRenderer.tsx")
    || fileRel.endsWith("components/preview/PreviewRenderer.tsx")) {
    return "artifact HTML iframe is sandboxed and tracked as the intentional artifact preview surface";
  }
  if (fileRel.includes("__tests__/")) {
    return "test fixture iframe exercises the plugin iframe hook without production exposure";
  }
  return "iframe surface has an explicit sandbox/isolation review requirement";
}

function allowedSrcDocReason(fileRel) {
  if (fileRel.endsWith("components/preview/ArtifactRenderer.tsx")
    || fileRel.endsWith("components/preview/PreviewRenderer.tsx")) {
    return "artifact srcDoc is intentionally isolated in a sandboxed iframe for HTML artifact previews";
  }
  return "";
}

function usage() {
  console.log(`html-surface-audit

Scans source files for HTML injection surfaces such as dangerouslySetInnerHTML,
srcDoc, raw Markdown HTML mode, and plugin iframe sandbox usage.

Options:
  --json              Print JSON only
  --report=<path>     Write JSON report
  --markdown=<path>   Write Markdown report
`);
}

if (help) {
  usage();
  process.exit(0);
}

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) return files;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name) || entry.name.startsWith("codia-")) continue;
      walk(path.join(dir, entry.name), files);
      continue;
    }
    if (entry.isFile() && EXTENSIONS.has(path.extname(entry.name))) {
      files.push(path.join(dir, entry.name));
    }
  }
  return files;
}

function rel(file) {
  return path.relative(ROOT, file).replace(/\\/g, "/");
}

function classify(fileRel, line, lineNumber) {
  const trimmed = line.trim();
  if (trimmed.startsWith("//") || trimmed.startsWith("/*") || trimmed.startsWith("*")) return [];
  const hits = [];

  if (trimmed.includes("getMdWithOpts") && /html\s*:\s*true/.test(trimmed)) {
    hits.push({
      kind: "raw-markdown-html",
      severity: fileRel.endsWith("utils/markdown.ts") ? "allowed" : "blocker",
      reason: fileRel.endsWith("utils/markdown.ts")
        ? "central markdown preview renderer sanitizes raw HTML output"
        : "raw Markdown HTML mode must be routed through renderMarkdownPreview()",
    });
  }

  if (trimmed.includes("dangerouslySetInnerHTML")) {
    const isKnownSafe = SAFE_HTML_HELPERS.some((token) => trimmed.includes(token))
      || (fileRel.endsWith("components/SkillViewerOverlay.tsx") && trimmed.includes("__html: rendered"));
    const reason = isKnownSafe ? allowedDangerousHtmlReason(fileRel, trimmed) : "";
    hits.push({
      kind: "dangerouslySetInnerHTML",
      severity: isKnownSafe ? "allowed" : "warning",
      reason: reason || "manual review required for HTML injection source",
    });
  }

  if (trimmed.includes("srcDoc=")) {
    const reason = allowedSrcDocReason(fileRel);
    hits.push({
      kind: "srcDoc",
      severity: reason ? "allowed" : "blocker",
      reason: reason || "srcDoc must be isolated or sanitized",
    });
  }

  if (trimmed === "<iframe" || trimmed.includes("<iframe")) {
    hits.push({
      kind: "iframe",
      severity: "allowed",
      reason: allowedIframeReason(fileRel, trimmed),
    });
  }

  return hits.map((hit) => ({
    file: fileRel,
    line: lineNumber,
    source: trimmed.slice(0, 220),
    ...hit,
  }));
}

const files = SCAN_ROOTS.flatMap((root) => walk(path.join(ROOT, root)));
const surfaces = [];

for (const file of files) {
  const fileRel = rel(file);
  const lines = fs.readFileSync(file, "utf-8").split(/\r?\n/);
  lines.forEach((line, index) => {
    surfaces.push(...classify(fileRel, line, index + 1));
  });
}

const blockers = surfaces.filter((item) => item.severity === "blocker");
const warnings = surfaces.filter((item) => item.severity === "warning");
const allowed = surfaces.filter((item) => item.severity === "allowed");
const report = {
  ok: blockers.length === 0,
  generatedAt: new Date().toISOString(),
  scannedFiles: files.length,
  counts: {
    blockers: blockers.length,
    warnings: warnings.length,
    allowed: allowed.length,
  },
  blockers,
  warnings,
  allowed,
  surfaces,
};

if (reportPath) {
  fs.mkdirSync(path.dirname(reportPath), { recursive: true });
  fs.writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);
}

if (markdownPath) {
  fs.mkdirSync(path.dirname(markdownPath), { recursive: true });
  fs.writeFileSync(markdownPath, renderMarkdown(report), "utf-8");
}

if (jsonOnly) {
  console.log(JSON.stringify(report, null, 2));
} else {
  console.log(`[html-surface-audit] scanned ${files.length} files; blockers=${blockers.length}; warnings=${warnings.length}`);
}

process.exit(report.ok ? 0 : 1);

function renderMarkdown(report) {
  const lines = [
    "# HTML Surface Audit",
    "",
    `Generated: ${report.generatedAt}`,
    `Scanned files: ${report.scannedFiles}`,
    `Blockers: ${report.counts.blockers}`,
    `Warnings: ${report.counts.warnings}`,
    "",
  ];
  for (const item of [...report.blockers, ...report.warnings]) {
    lines.push(`- ${item.severity.toUpperCase()} ${item.file}:${item.line} ${item.kind} - ${item.reason}`);
  }
  return `${lines.join("\n")}\n`;
}
