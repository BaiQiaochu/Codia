function resolveLocale(): LocaleKey {
  const locale = String(window.i18n?.locale || 'zh-CN').toLowerCase();
  return locale.startsWith('zh') ? 'zh' : 'en';
}

function lookup(tree: CopyTree, path: string): string | CopyTree | undefined {
  return path.split('.').reduce<string | CopyTree | undefined>((value, key) => {
    if (!value || typeof value === 'string') return value;
    return value[key];
  }, tree);
}

export function settingsCopy(path: string, vars?: Record<string, string | number>): string {
  const locale = resolveLocale();
  const raw = lookup(COPY[locale], path) ?? lookup(COPY.en, path) ?? lookup(COPY.zh, path);
  let text = typeof raw === 'string' ? raw : path;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value));
    }
  }
  return text;
}

